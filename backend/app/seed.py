"""Initial data for a fresh installation.

* Always create the login accounts shown in `.env`.
* On an empty database, create all 500 extensions (100-599) so the PBX has
  endpoints from the first start.  Passwords match the original demo
  configuration (`100pass`, ...).
* When `SEED_DEMO_DATA` is true, add a small set of people to the directory
  and assign a few of them an extension.

Seeding is additive: existing users and extensions are never overwritten.
"""

from __future__ import annotations

from sqlalchemy.orm import Session

from .config import settings
from .models import Extension, User
from .pbx import DEPARTMENTS
from .security import hash_password

DEMO_PEOPLE = [
    ("Amine", "Benali", "administration"),
    ("Sara", "Haddad", "administration"),
    ("Yacine", "Messaoud", "finance"),
    ("Lina", "Boukhalfa", "finance"),
    ("Karim", "Cherif", "it"),
    ("Nadia", "Djebbar", "it"),
    ("Omar", "Ferhat", "support"),
    ("Meriem", "Gacem", "support"),
    ("Walid", "Hamidi", "management"),
    ("Imane", "Slimani", "management"),
]


def _get_account(db: Session, username: str) -> User | None:
    return db.query(User).filter(User.username == username).first()


def _create_account(
    db: Session,
    username: str,
    password: str,
    full_name: str,
    email: str,
    department: str,
    role: str,
) -> None:
    if _get_account(db, username) is not None:
        return
    if db.query(User).filter(User.email == email).first() is not None:
        return

    db.add(
        User(
            username=username,
            password_hash=hash_password(password),
            full_name=full_name,
            email=email,
            department=department,
            role=role,
            is_active=True,
        )
    )


def _seed_accounts(db: Session) -> None:
    admin_username = settings.seed_admin_username.strip().lower() or "admin"
    _create_account(
        db,
        admin_username,
        settings.seed_admin_password,
        "System Administrator",
        f"{admin_username}@appliance.local",
        "administration",
        "admin",
    )

    if settings.seed_demo_data:
        _create_account(
            db,
            "operator",
            "operator",
            "Call Center Operator",
            "operator@appliance.local",
            "support",
            "operator",
        )
        _create_account(
            db,
            "viewer",
            "viewer",
            "Read-only Viewer",
            "viewer@appliance.local",
            "administration",
            "viewer",
        )


def _seed_extensions(db: Session) -> dict[str, Extension]:
    """Create 100-599 when the table is empty and return a number -> object map."""
    extensions = {
        extension.number: extension for extension in db.query(Extension).all()
    }
    if extensions:
        return extensions

    for number in range(100, 600):
        extension = Extension(
            number=str(number),
            secret=f"{number}pass",
            enabled=True,
        )
        db.add(extension)
        extensions[extension.number] = extension
    return extensions


def _seed_people(db: Session, extensions: dict[str, Extension]) -> None:
    if not settings.seed_demo_data:
        return

    created: list[User] = []
    for index, (first, last, department) in enumerate(DEMO_PEOPLE):
        email = f"{first}.{last}{index}@appliance.local".lower()
        if db.query(User).filter(User.email == email).first() is not None:
            continue
        user = User(
            full_name=f"{first} {last}",
            email=email,
            department=department,
            role="viewer",
            is_active=True,
        )
        db.add(user)
        created.append(user)

    if not created:
        return

    # User ids are generated by the database, so flush before assigning.
    db.flush()

    counters = {department["id"]: 0 for department in DEPARTMENTS}
    for user in created:
        department = next(
            (item for item in DEPARTMENTS if item["id"] == user.department), None
        )
        if department is None:
            continue
        number = str(department["from"] + counters[department["id"]])
        counters[department["id"]] += 1
        extension = extensions.get(number)
        if extension is not None:
            extension.user_id = user.id


def seed_database(db: Session) -> None:
    """Create the default accounts, extensions and demo directory."""
    _seed_accounts(db)
    extensions = _seed_extensions(db)
    _seed_people(db, extensions)
    db.commit()
