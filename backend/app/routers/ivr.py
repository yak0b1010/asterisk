VALID_DESTINATION_TYPES = {
    "extension",
    "queue",
    "voicemail",
    "ivr",
    "conference",
    "playback",
}

_CREATE_FIELDS = {
    "name",
    "description",
    "greeting_sound",
    "invalid_sound",
    "timeout",
    "max_attempts",
    "active",
    "options",
}
_UPDATE_FIELDS = _CREATE_FIELDS - {"options"}
_OPTION_FIELDS = {
    "digit",
    "destination_type",
    "destination",
    "description",
    "sort_order",
}
_OPTIONS_FIELDS = {"options"}


def _valid_sound(value: str) -> bool:
    if not value or len(value) > 255:
        return False
    if any(ch in " \t\r\n\\" for ch in value):
        return False
    return ".." not in value


def _find(session: Session, key: str) -> IVRMenu:
    key = (key or "").strip()
    if not key:
        raise bad_request("IVR id or name is required")
    if parse_uuid(key):
        menu = session.get(IVRMenu, key)
    else:
        menu = session.scalars(select(IVRMenu).where(IVRMenu.name == key)).first()
    if menu is None:
        raise not_found("IVR menu")
    return menu


def _load_options(session: Session, menu_id: str) -> list[IVRMenuOption]:
    return list(
        session.scalars(
            select(IVRMenuOption)
            .where(IVRMenuOption.menu_id == menu_id)
            .order_by(IVRMenuOption.sort_order.asc(), IVRMenuOption.digit.asc())
        ).all()
    )


def _validate_options(raw: Any) -> list[IVRMenuOption]:
    if raw is None:
        return []
    if not isinstance(raw, list):
        raise bad_request("options must be an array")
    seen: set[str] = set()
    options: list[IVRMenuOption] = []
    for item in raw:
        if not isinstance(item, dict):
            raise bad_request("options must contain objects")
        reject_unknown(item, _OPTION_FIELDS)
        digit = to_str(item, "digit").strip()
        destination_type = to_str(item, "destination_type").strip()
        destination = to_str(item, "destination").strip()
        if len(digit) != 1 or digit not in "0123456789*#":
            raise bad_request("option digit must be one of 0-9, * or #")
        if digit in seen:
            raise bad_request(f"option digit {digit} is duplicated")
        seen.add(digit)
        if destination_type not in VALID_DESTINATION_TYPES:
            raise bad_request(
                f'option destination_type "{destination_type}" is not supported'
            )
        if (
            not destination
            or len(destination) > 128
            or any(ch in " \t\r\n" for ch in destination)
        ):
            raise bad_request(
                f"option {digit} destination is required and must not contain whitespace"
            )
        if destination_type == "extension" and not valid_number(destination, 1, 16):
            raise bad_request(
                f"option {digit} destination must be an extension number"
            )
        options.append(
            IVRMenuOption(
                digit=digit,
                destination_type=destination_type,
                destination=destination,
                description=clean(to_str(item, "description"), 255),
                sort_order=to_int(item, "sort_order"),
            )
        )
    options.sort(key=lambda option: option.sort_order)
    return options


def _generate_dialplan(menu: IVRMenu, options: list[IVRMenuOption]) -> str:
    lines = [
        f";; IVR menu {menu.name} (generated by asterisk-backend)",
        f"[ivr-{menu.name}]",
        "exten => s,1,Answer()",
        f" same => n,Set(TIMEOUT(digit)={menu.timeout})",
        f" same => n,Background({menu.greeting_sound})",
        f" same => n,WaitExten({menu.timeout})",
    ]
    for option in options:
        if option.destination_type == "extension":
            lines.append(
                f"exten => {option.digit},1,Goto(internal,{option.destination},1)"
            )
        elif option.destination_type == "queue":
            lines.append(f"exten => {option.digit},1,Queue({option.destination})")
        elif option.destination_type == "voicemail":
            lines.append(
                f"exten => {option.digit},1,VoiceMail({option.destination}@internal)"
            )
        elif option.destination_type == "ivr":
            lines.append(
                f"exten => {option.digit},1,Goto(ivr-{option.destination},s,1)"
            )
        elif option.destination_type == "conference":
            lines.append(
                f"exten => {option.digit},1,ConfBridge({option.destination})"
            )
        elif option.destination_type == "playback":
            lines.append(f"exten => {option.digit},1,Playback({option.destination})")
    invalid = menu.invalid_sound or "invalid"
    lines.append(f"exten => i,1,Playback({invalid})")
    lines.append(f" same => n,Goto(ivr-{menu.name},s,1)")
    lines.append("exten => t,1,Hangup()")
    return "\n".join(lines) + "\n"


@router.get("")
@router.get("/")
def list_ivr(
    request: Request,
    session: Session = Depends(get_db),
    _: User = Depends(require_permission("ivr.read")),
):
    page, limit, offset = pagination(request)
    conditions = []
    search = (request.query_params.get("search") or "").strip()
    if search:
        like = f"%{search}%"
        conditions.append(
            or_(IVRMenu.name.ilike(like), IVRMenu.description.ilike(like))
        )
    active, present = query_bool(request, "active")
    if present:
        conditions.append(IVRMenu.active.is_(active))
    total = session.scalar(
        select(func.count()).select_from(IVRMenu).where(*conditions)
    ) or 0
    menus = session.scalars(
        select(IVRMenu)
        .where(*conditions)
        .order_by(IVRMenu.name.asc())
        .limit(limit)
        .offset(offset)
    ).all()
    by_menu: dict[str, list[IVRMenuOption]] = {}
    if menus:
        options = session.scalars(
            select(IVRMenuOption)
            .where(IVRMenuOption.menu_id.in_([menu.id for menu in menus]))
            .order_by(IVRMenuOption.sort_order.asc(), IVRMenuOption.digit.asc())
        ).all()
        for option in options:
            by_menu.setdefault(option.menu_id, []).append(option)
    return respond_list(
        [ivr_response(menu, by_menu.get(menu.id, [])) for menu in menus],
        page,
        limit,
        total,
    )


@router.post("", status_code=201)
@router.post("/", status_code=201)
async def create_ivr(
    request: Request,
    session: Session = Depends(get_db),
    _: User = Depends(require_permission("ivr.write")),
):
    body = await read_json(request)
    reject_unknown(body, _CREATE_FIELDS)
    name = to_str(body, "name").strip()
    if not valid_slug(name, 120):
        raise bad_request(
            "name must be 1-120 letters, digits, dot, underscore or hyphen"
        )
    greeting = to_str(body, "greeting_sound") or "ivr-welcome"
    invalid_sound = to_str(body, "invalid_sound")
    if not _valid_sound(greeting) or (
        invalid_sound != "" and not _valid_sound(invalid_sound)
    ):
        raise bad_request(
            "greeting_sound and invalid_sound must be valid sound paths"
        )
    timeout = to_int(body, "timeout") or 5
    max_attempts = to_int(body, "max_attempts") or 3
    if timeout < 1 or timeout > 30:
        raise bad_request("timeout must be between 1 and 30 seconds")
    if max_attempts < 1 or max_attempts > 10:
        raise bad_request("max_attempts must be between 1 and 10")
    options = _validate_options(body.get("options"))
    active = to_optional_bool(body, "active")
    menu = IVRMenu(
        name=name,
        description=clean(to_str(body, "description"), 255),
        greeting_sound=greeting,
        invalid_sound=invalid_sound,
        timeout=timeout,
        max_attempts=max_attempts,
        active=True if active is None else active,
    )
    try:
        session.add(menu)
        session.flush()
        for option in options:
            option.menu_id = menu.id
            session.add(option)
        session.commit()
    except Exception as exc:
        session.rollback()
        if is_unique_violation(exc):
            return conflict("IVR menu name or option digit already exists")
        raise
    return respond(ivr_response(menu, options), status=201)


@router.get("/{ivr_id}")
def get_ivr(
    ivr_id: str,
    session: Session = Depends(get_db),
    _: User = Depends(require_permission("ivr.read")),
):
    menu = _find(session, ivr_id)
    return respond(ivr_response(menu, _load_options(session, menu.id)))


@router.put("/{ivr_id}")
@router.patch("/{ivr_id}")
async def update_ivr(
    ivr_id: str,
    request: Request,
    session: Session = Depends(get_db),
    _: User = Depends(require_permission("ivr.write")),
):
    menu = _find(session, ivr_id)
    body = await read_json(request)
    reject_unknown(body, _UPDATE_FIELDS)
    changed = False

    name = to_optional_str(body, "name")
    if name is not None:
        name = name.strip()
        if not valid_slug(name, 120):
            raise bad_request(
                "name must be 1-120 letters, digits, dot, underscore or hyphen"
            )
        menu.name = name
        changed = True
    description = to_optional_str(body, "description")
    if description is not None:
        menu.description = clean(description, 255)
        changed = True
    greeting = to_optional_str(body, "greeting_sound")
    if greeting is not None:
        if not _valid_sound(greeting):
            raise bad_request("greeting_sound must be a valid sound path")
        menu.greeting_sound = greeting
        changed = True
    invalid_sound = to_optional_str(body, "invalid_sound")
    if invalid_sound is not None:
        if invalid_sound != "" and not _valid_sound(invalid_sound):
            raise bad_request("invalid_sound must be a valid sound path")
        menu.invalid_sound = invalid_sound
        changed = True
    timeout = to_optional_int(body, "timeout")
    if timeout is not None:
        if timeout < 1 or timeout > 30:
            raise bad_request("timeout must be between 1 and 30 seconds")
        menu.timeout = timeout
        changed = True
    max_attempts = to_optional_int(body, "max_attempts")
    if max_attempts is not None:
        if max_attempts < 1 or max_attempts > 10:
            raise bad_request("max_attempts must be between 1 and 10")
        menu.max_attempts = max_attempts
        changed = True
    active = to_optional_bool(body, "active")
    if active is not None:
        menu.active = active
        changed = True
    if not changed:
        raise bad_request("no supported fields supplied")

    menu.updated_at = utcnow()
    try:
        session.commit()
    except Exception as exc:
        session.rollback()
        if is_unique_violation(exc):
            return conflict("IVR menu name already exists")
        raise
    session.refresh(menu)
    return respond(ivr_response(menu, _load_options(session, menu.id)))


@router.delete("/{ivr_id}")
def delete_ivr(
    ivr_id: str,
    session: Session = Depends(get_db),
    _: User = Depends(require_permission("ivr.write")),
):
    menu = _find(session, ivr_id)
    session.execute(
        delete(IVRMenuOption).where(IVRMenuOption.menu_id == menu.id)
    )
    session.delete(menu)
    session.commit()
    from ..responses import no_content

    return no_content()


@router.put("/{ivr_id}/options")
async def replace_ivr_options(
    ivr_id: str,
    request: Request,
    session: Session = Depends(get_db),
    _: User = Depends(require_permission("ivr.write")),
):
    menu = _find(session, ivr_id)
    body = await read_json(request)
    reject_unknown(body, _OPTIONS_FIELDS)
    options = _validate_options(body.get("options"))
    try:
        session.execute(
            delete(IVRMenuOption).where(IVRMenuOption.menu_id == menu.id)
        )
        for option in options:
            option.menu_id = menu.id
            session.add(option)
        session.commit()
    except Exception as exc:
        session.rollback()
        if is_unique_violation(exc):
            return conflict("option digit already exists in this menu")
        raise
    return respond([ivr_option_response(option) for option in options])


@router.post("/{ivr_id}/reload")
def reload_ivr(
    ivr_id: str,
    request: Request,
    _: User = Depends(require_permission("ivr.write")),
):
    return reload_asterisk(request, "dialplan")


@router.get("/{ivr_id}/dialplan")
def ivr_dialplan(
    ivr_id: str,
    session: Session = Depends(get_db),
    _: User = Depends(require_permission("ivr.read")),
):
    menu = _find(session, ivr_id)
    options = _load_options(session, menu.id)
    return Response(
        content=_generate_dialplan(menu, options),
        media_type="text/plain; charset=utf-8",
        headers={
            "Content-Disposition": f'attachment; filename="ivr-{menu.name}.conf"'
        },
    )
